def infer_discipline(text: str) -> str | None:
    upper = (text or "").upper()
    if not upper:
        return None
    # 1) 图号前缀优先（最强信号）
    prefix = re.match(r"^\s*([A-Z]+|[一-鿿]+)\s*[-_—－–]?\s*\d+", upper)
    if prefix:
        token = prefix.group(1)
        for discipline, keywords in PREFIX_RULES:
            if token in {keyword.upper() for keyword in keywords}:
                return discipline
    # 2) 全文加权投票，得分最高的专业胜出
    scores: dict[str, int] = {}
    for discipline, keyword, weight in SCORED_KEYWORDS:
        if keyword.upper() in upper:
            scores[discipline] = scores.get(discipline, 0) + weight
    if not scores:
        return None
    return max(scores.items(), key=lambda kv: kv[1])[0]
